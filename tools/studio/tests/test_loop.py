"""Loop tests on a throwaway git repo; radar and LLM are stubbed (no network)."""

import json
import os
import shutil
import subprocess
from pathlib import Path

import yaml

from noirstudio import loop, radar as radar_mod

ROOT = Path(__file__).resolve().parents[3]
GIT_ENV = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t",
           "GIT_COMMITTER_EMAIL": "t@t"}


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True, env=GIT_ENV).stdout


def _make_repo(tmp_path: Path) -> Path:
    repo = tmp_path / "repo"
    (repo / "specs").mkdir(parents=True)
    shutil.copy(ROOT / "specs" / "agent-log-001.yaml", repo / "specs" / "agent-log-001.yaml")
    (repo / "radar.yaml").write_text(radar_mod.DEFAULT_CONFIG, encoding="utf-8")
    (repo / ".gitignore").write_text("renders/\n", encoding="utf-8")
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "init")
    return repo


